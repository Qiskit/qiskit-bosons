"""Mode rotation gate."""

from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING

import numpy as np
import scipy.linalg

from .. import BosonicGate

if TYPE_CHECKING:
    from .synthesis import B2BSynthesisPlugin


class ModeRotation(BosonicGate):
    r"""Implements a passive linear-optical mode transformation.

    Given an :math:`M \times M` unitary matrix :math:`U` (``rotation_unitary``), this gate implements
    the basis change that maps the creation operators as

    .. math::

        b^\dagger_i \mapsto \sum_j U_{ji} \, b^\dagger_j \, ,

    equivalently the many-body unitary

    .. math::

        \exp\left(\sum_{ij} \log(U)_{ij} \, b^\dagger_i b_j\right) \, .

    The number of bosonic modes the gate acts on is the dimension :math:`M` of ``rotation_unitary``.

    .. rubric:: Action on the occupation sectors

    Restricted to the *single-particle* sector, the gate is the :math:`M \times M` matrix :math:`U`
    itself. It acts on *every* occupation sector at once, however: the two-particle block is the
    symmetric square of :math:`U` (carrying the :math:`\sqrt{2}` factors), and so on up to the
    truncation.

    .. rubric:: Synthesis

    Breaking this gate down in bosonic space (into a circuit of smaller :class:`.Evolution` gates) is
    what the :attr:`~.BosonicGate.synthesis` attribute governs. It is ``None`` by default, which
    leaves the gate whole: there is no preferred decomposition, and a method such as
    :class:`.BosonicClementsDecomposition` is chosen explicitly, either here or for a whole circuit
    with the :class:`.B2BSynthesis` transpiler pass. The circuit it produces implements the same
    unitary as the gate (on the untruncated Fock space), and it `is` the definition of the gate.

    A gate that is left whole reaches the boson-to-qubit stage, which needs a plugin registered for
    ``ModeRotation`` to lower it. The library ships none, because the transpiler preset decomposes
    the gate in bosonic space first. A plugin that maps the generator of
    :meth:`to_operator` directly is a few lines long; see :ref:`mode_rotation_direct_explanation`.
    The two-mode :meth:`beamsplitter` follows the convention of Clements et al. [1]_

    .. warning::
       Because this gate mixes occupation sectors *within* a mode, a truncation that merely bounds the
       initial per-mode occupation is not sufficient. Acting on :math:`\lvert 1, 1 \rangle`, a
       two-mode rotation populates :math:`\lvert 2, 0 \rangle`, so a cutoff of ``max_occupation=1``
       silently produces a wrong state. The cutoff must bound the **total** boson number reachable in
       any single mode. This matters most when the modes have different cutoffs: a rotation moves
       bosons between modes, so each mode that can receive them needs a cutoff that covers what it
       can receive, not only what it starts with.

    This gate is `passive`: it conserves the total boson number (it is generated by
    number-conserving :math:`b^\dagger_i b_j` terms). The `active` Gaussian operations --
    squeezing and displacement -- do not conserve boson number and are not expressible as a
    ``ModeRotation``.

    .. [1] W. R. Clements et al., Optimal design for universal multiport interferometers,
       Optica 3, 1460 (2016), `arXiv:1603.08788 <https://arxiv.org/abs/1603.08788>`_.
    """

    def __init__(
        self,
        rotation_unitary: np.ndarray,
        *,
        synthesis: B2BSynthesisPlugin | None = None,
    ) -> None:
        r"""Initializing an instance of this gate can be done with the arguments listed below.

        Args:
            rotation_unitary: the :math:`M \times M` unitary matrix :math:`U` defining the mode
                transformation via :math:`b^\dagger_i \mapsto \sum_j U_{ji} b^\dagger_j`. It must be
                square and unitary; this is the caller's responsibility and is not verified.
            synthesis: the boson-to-boson synthesis method with which to decompose this gate, when
                it gets decomposed at all. If ``None`` (the default), the gate has no bosonic
                decomposition and :meth:`~.BosonicCircuit.decompose` leaves it in place.
        """
        self.rotation_unitary = np.asarray(rotation_unitary, dtype=complex)
        """The unitary matrix representing the mode-transformation coefficients."""

        super().__init__("ModeRotation", self.rotation_unitary.shape[0], [], synthesis=synthesis)

    def inverse(self, annotated: bool = False) -> ModeRotation:
        r"""Returns the inverse of this gate, whose rotation unitary is :math:`U^\dagger`.

        Args:
            annotated: ignored. The inverse of this gate is another :class:`.ModeRotation`, so it
                never needs to be an :class:`~qiskit.circuit.AnnotatedOperation`.

        Returns:
            A :class:`.ModeRotation` with the same synthesis method.
        """
        return ModeRotation(self.rotation_unitary.conj().T, synthesis=self.synthesis)

    def __eq__(self, other: object) -> bool:
        """Compares two gates by their rotation unitary."""
        if not isinstance(other, ModeRotation):
            return NotImplemented
        return bool(np.array_equal(self.rotation_unitary, other.rotation_unitary))

    def __hash__(self) -> int:
        """Hashes this gate by its rotation unitary."""
        return hash(
            (type(self).__name__, self.rotation_unitary.shape, self.rotation_unitary.tobytes())
        )

    @classmethod
    def beamsplitter(cls, theta: float, phi: float = 0.0) -> ModeRotation:
        r"""Constructs the two-mode beamsplitter.

        Following the Clements convention, [1]_ the two-mode transfer matrix is

        .. math::

            T(\theta, \phi) = \begin{pmatrix}
                e^{i\phi}\cos\theta & -\sin\theta \\
                e^{i\phi}\sin\theta & \cos\theta
            \end{pmatrix} \, ,

        which together with the single-mode phase shifts generates any :math:`U(M)` when arranged in
        the Clements mesh.

        Args:
            theta: the mixing angle :math:`\theta`. A value of :math:`\pi/4` gives the balanced
                50:50 beamsplitter.
            phi: the relative phase :math:`\phi`.

        Returns:
            A two-mode :class:`ModeRotation`.
        """
        cos, sin = np.cos(theta), np.sin(theta)
        phase = np.exp(1j * phi)
        return cls(np.array([[phase * cos, -sin], [phase * sin, cos]], dtype=complex))

    @classmethod
    def phase_shift(cls, phases: Sequence[float]) -> ModeRotation:
        r"""Constructs a product of single-mode phase shifts.

        Each mode :math:`m` acquires :math:`b^\dagger_m \mapsto e^{i \varphi_m} b^\dagger_m`, that
        is, the rotation unitary is :math:`\mathrm{diag}(e^{i\varphi_0}, \ldots)`.

        Args:
            phases: the phase :math:`\varphi_m` applied to each mode.

        Returns:
            A :class:`ModeRotation` that is diagonal in the mode basis.
        """
        return cls(np.diag(np.exp(1j * np.asarray(phases, dtype=float))))

    @classmethod
    def from_generator(cls, generator: np.ndarray) -> ModeRotation:
        r"""Constructs the rotation from an anti-Hermitian generator.

        Returns the gate whose ``rotation_unitary`` is :math:`\exp(K)` for the given :math:`K`. For
        the result to be unitary, :math:`K` must be anti-Hermitian
        (:math:`K^\dagger = -K`); this is the caller's responsibility and is not verified.

        Args:
            generator: the :math:`M \times M` anti-Hermitian generator :math:`K`.

        Returns:
            A :class:`ModeRotation` with ``rotation_unitary`` :math:`= \exp(K)`.
        """
        return cls(scipy.linalg.expm(np.asarray(generator, dtype=complex)))

    def generator(self) -> np.ndarray:
        r"""Returns the anti-Hermitian generator :math:`\log(U)` of this rotation.

        This is the matrix :math:`K` such that the many-body unitary is
        :math:`\exp(\sum_{ij} K_{ij} b^\dagger_i b_j)`, which is what a synthesis plugin exponentiates.
        """
        return np.asarray(scipy.linalg.logm(self.rotation_unitary), dtype=complex)

    def to_operator(self, tol: float = 1e-12):
        r"""Returns the Hermitian generator of this gate as a :class:`.BosonOperator`.

        Builds :math:`H = \sum_{ij} \mathrm{i} \log(U)_{ij} \, b^\dagger_i b_j`, the Hermitian operator
        for which :math:`e^{-\mathrm{i} H}` is this gate. That is exactly the form of an
        :class:`.Evolution` gate at unit time, which makes this the bridge from the gate's matrix
        form to the operator algebra, and hence to any boson-to-qubit encoding.

        The matrix logarithm of a unitary is anti-Hermitian only up to round-off, so the result is
        built from the anti-Hermitian part of :math:`\log(U)` and is *exactly* Hermitian, as a
        :class:`~qiskit.circuit.library.PauliEvolutionGate` requires of the mapped operator.

        Args:
            tol: entries of :math:`H` with magnitude at or below this are dropped. ``logm`` of a
                sparse or block-diagonal unitary leaves round-off in nominally-zero entries; keeping
                them would bloat the operator with meaningless terms.

        Returns:
            The Hermitian generator as a :class:`~qiskit_bosons.operators.BosonOperator`.
        """
        from qiskit_bosons.operators import BosonOperator, ann, cre

        log_mat = self.generator()
        hermitian = 1j * 0.5 * (log_mat - log_mat.conj().T)
        terms = {
            (cre(i), ann(j)): complex(hermitian[i, j])
            for i in range(hermitian.shape[0])
            for j in range(hermitian.shape[1])
            if abs(hermitian[i, j]) > tol
        }
        return BosonOperator.from_dict(terms)  # type: ignore[arg-type]
